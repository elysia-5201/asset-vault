async function artPng(label, hue, w = 768, h = 768) {
  const svg =
    '<svg xmlns="http://www.w3.org/2000/svg" width="' + w + '" height="' + h + '">' +
    '<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">' +
    '<stop offset="0%" stop-color="hsl(' + hue + ',85%,74%)"/>' +
    '<stop offset="100%" stop-color="hsl(' + ((hue + 70) % 360) + ',70%,42%)"/>' +
    '</linearGradient></defs>' +
    '<rect width="100%" height="100%" fill="url(#g)"/>' +
    '<circle cx="' + (w * 0.72) + '" cy="' + (h * 0.3) + '" r="' + (w * 0.16) + '" fill="#ffffff22"/>' +
    '<circle cx="' + (w * 0.3) + '" cy="' + (h * 0.74) + '" r="' + (w * 0.22) + '" fill="#00000018"/>' +
    '<text x="50%" y="52%" font-size="' + Math.round(w / 16) + '" text-anchor="middle" fill="#ffffffe0" font-family="sans-serif">' + label + '</text>' +
    '</svg>';
  return sharp(Buffer.from(svg)).png().toBuffer();
}

function tarHeader(name, size, mtime) {
  const b = Buffer.alloc(512);
  b.write(name, 0, 100, "utf8");
  b.write("000644 \0", 100, 8);
  b.write("000000 \0", 108, 8);
  b.write("000000 \0", 116, 8);
  b.write(size.toString(8).padStart(11, "0") + " ", 124, 12);
  b.write(Math.floor(mtime / 1000).toString(8).padStart(11, "0") + " ", 136, 12);
  b.write("        ", 148, 8);
  b.write("0", 156, 1);
  b.write("ustar\0" + "00", 257, 8);
  let sum = 0; for (const c of b) sum += c;
  b.write(sum.toString(8).padStart(6, "0") + "\0 ", 148, 8);
  return b;
}
function tarEntry(name, data, mtime) {
  const pad = Buffer.alloc((512 - (data.length % 512)) % 512);
  return Buffer.concat([tarHeader(name, data.length, mtime), data, pad]);
}

/** 造一个「结构像真包」的 unitypackage：N 个资产 + preview.png。 */
async function makeUnityPackage(assets, previewPng, mtime) {
  const parts = [];
  for (const rel of assets) {
    const guid = randomBytes(16).toString("hex");
    const body = rel.endsWith(".txt")
      ? Buffer.from("Demo pack. Generated by scripts/make-demo-library.mjs\n")
      : randomBytes(4096 + Math.floor(Math.random() * 20000));
    parts.push(tarEntry(guid + "/asset", body, mtime));
    parts.push(tarEntry(guid + "/asset.meta", Buffer.from("fileFormatVersion: 2\nguid: " + guid + "\n"), mtime));
    parts.push(tarEntry(guid + "/pathname", Buffer.from("Assets/DemoPack/" + rel), mtime));
  }
  if (previewPng) {
    const guid = randomBytes(16).toString("hex");
    parts.push(tarEntry(guid + "/preview.png", previewPng, mtime));
    parts.push(tarEntry(guid + "/pathname", Buffer.from("Assets/DemoPack/Preview.png"), mtime));
  }
  parts.push(Buffer.alloc(1024));
  return gzipSync(Buffer.concat(parts));
}

function sevenZipPath() {
  const bin = require("7zip-bin").path7za;
  try { chmodSync(bin, 0o755); } catch { /* 已可执行或不允许 */ }
  return bin;
}

if (existsSync(outDir)) rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
const work = join(outDir, ".work");
mkdirSync(work, { recursive: true });
const z7 = sevenZipPath();
const mtime = Date.now();

for (const p of PACKS) {
  const pkgName = p.label.replace(/[^\w.-]+/g, "_") + ".unitypackage";
  const pkgPath = join(work, pkgName);
  // 包内路径按 avatar 分目录，和真实素材一致（匹配器据此产出 unitypackage_path 证据）
  const assetPaths = [];
  for (const av of p.avatars ?? []) {
    for (const rel of p.assets ?? []) {
      const dir = rel.includes("/") ? rel.slice(0, rel.lastIndexOf("/")) : "";
      const base = rel.includes("/") ? rel.slice(rel.lastIndexOf("/") + 1) : rel;
      assetPaths.push(dir ? dir + "/" + av + "/" + base : av + "/" + base);
    }
  }
  for (const rel of p.assets ?? []) assetPaths.push("Common/" + rel);
  writeFileSync(pkgPath, await makeUnityPackage(assetPaths, await artPng(p.label, p.hue), mtime));
  writeFileSync(join(work, "preview_1.png"), await artPng(p.label + " 01", p.hue));
  writeFileSync(join(work, "preview_2.png"), await artPng(p.label + " 02", (p.hue + 40) % 360));
  writeFileSync(join(work, "ReadMe.txt"), Buffer.from("Demo asset for screenshots.\n"));
  const zip = join(outDir, p.file + ".zip");
  execFileSync(z7, ["a", "-tzip", "-mx=1", zip, pkgName, "preview_1.png", "preview_2.png", "ReadMe.txt"], { cwd: work, stdio: "ignore" });
  console.log("  " + p.file + ".zip");
}
rmSync(work, { recursive: true, force: true });
console.log("demo library -> " + outDir + "（" + PACKS.length + " 个包）");